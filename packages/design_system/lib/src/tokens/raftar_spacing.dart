/// Spacing scale on a 4-point grid. Use these instead of magic numbers so
/// layouts stay rhythmically consistent across all three apps.
abstract final class RaftarSpacing {
  static const double xxs = 2;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
  static const double huge = 48;

  /// Default screen edge padding.
  static const double screen = lg;
}

/// Corner-radius scale.
abstract final class RaftarRadii {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double pill = 999;
}
